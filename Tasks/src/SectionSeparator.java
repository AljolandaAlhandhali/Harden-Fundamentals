/*
Description:
Create a program that prints three sections, each separated by a line of dashes.

Acceptance Criteria:
The output displays three section titles, each followed by a line of dashes.
The separator lines are consistent in length.
No loops are required for this problem.
Solution can be written using multiple print statements if needed.

Expected Input/Output:

Output:
Section 1: Introduction
--------------------
Section 2: Methods
--------------------
Section 3: Conclusion
--------------------
*/

public class SectionSeparator {
    public static void main(String[] args) {
        System.out.print("Section 1: Introduction\n");
        System.out.print("--------------------\n");
        System.out.print("Section 2: Methods\n");
        System.out.print("--------------------\n");
        System.out.print("Section 3: Conclusion\n");
        System.out.print("--------------------\n");
    }
}

