public class ArrayExample {
    public static void main(String[] args) {
        String[] names = new String[3];
        names[0] = "Al-Jolanda";
        names[1] = "Ali";
        names[2] = "Sara";

        for (int i = 0; i < names.length; i++){
            System.out.println(names[i]);
        }
    }
}
