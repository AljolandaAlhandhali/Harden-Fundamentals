/*
Description:
Create a program that prints a weekly calendar header, showing days of the week separated by tabs and framed by lines.

Acceptance Criteria:
The output displays a header with days of the week, separated by tabs.
The header is framed by lines above and below.
No loops are required for this problem.
Solution can be written using multiple print statements if needed.

Expected Input/Output:
Output:
=================================
   Mon	Tue	Wed	Thu	Fri	Sat	Sun
=================================
*/

public class TheWeeklyHeader {
    public static void main(String[] args) {
        System.out.println("=================================");
        System.out.println("   Mon\tTue\tWed\tThu\tFri\tSat\tSun");
        System.out.println("=================================");
    }
}
