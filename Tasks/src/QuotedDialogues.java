/*
Description:
Write a program that prints a conversation between a teacher and a student, using proper quotation marks and line breaks.

Acceptance Criteria:
The output displays each line of dialogue with correct quotation marks.
Each speaker's line appears on a new line.
No loops are required for this problem.
Solution can be written using multiple print statements if needed.

Expected Input/Output:
Output:
Teacher: "What is your name?"
Student: "My name is Alex."
Teacher: "Welcome, Alex!"
*/

public class QuotedDialogues {
    public static void main(String[] args) {
        System.out.println("Teacher: \"What is your name?\"");
        System.out.println("Student: \"My name is Alex.\"");
        System.out.println("Teacher: \"Welcome, Alex!\"");
    }
}
