/*
Description:
Write a program that prints a single line of 50 equal signs (=) as a separator.

Acceptance Criteria:
The output displays exactly 50 equal signs on one line.
No loops are required for this problem.
Solution can be written using a single print statement.

Expected Input/Output:
Output:
==================================================
*/
public class TheLongSeparator {
    public static void main(String[] args) {
        System.out.println("=".repeat(50));
        System.out.println("OR");
        System.out.println("==================================================");

    }
}
